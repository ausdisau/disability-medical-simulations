export const EVIDENCE_LABELS = Object.freeze(['FULL_TEXT_INSPECTED','ABSTRACT_INSPECTED','METADATA_ONLY','USER_SUPPLIED','SECONDARY_DESCRIPTION']);
export const EVIDENCE_DOMAINS = Object.freeze(['clinical','baseline','access','ethics','human_system','education']);
export function validateEvidence(records=EVIDENCE){
  const seen=new Set();
  for (const r of records) {
    if (!r.id || seen.has(r.id) || !EVIDENCE_LABELS.includes(r.evidence_label) || !EVIDENCE_DOMAINS.includes(r.domain) ||
        !['PubMed','JSTOR'].includes(r.database) || !r.url?.startsWith('https://') || !r.limitations) return false;
    seen.add(r.id);
  }
  return true;
}
export function findEvidence(id){return EVIDENCE.find(x=>x.id===id)||null;}
export function proposedEducationalUse(id){
  const paper=findEvidence(id);
  if (!paper) return {status:'NOT_FOUND',clinicalEffect:false,authorisesTreatment:false};
  return Object.freeze({status:'REVIEW_REQUIRED',sourceId:paper.id,domain:paper.domain,
    proposedUse:paper.simulation_implication,clinicalEffect:false,authorisesTreatment:false,
    requiredReview:['qualified clinical reviewer','paid relevant disability lived-experience reviewer','versioned scenario rule review']});
}
