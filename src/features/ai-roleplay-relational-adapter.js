import { deriveRoleplayContext, summarizeRelationalState } from "./biosocial-relational-substrate.js";

function assertActor(state, actorId, field) {
  const actor = state?.actors?.[actorId];
  if (!actor) throw new RangeError(`${field} must identify an actor in the relational substrate.`);
  return actor;
}

function band(value, labels) {
  if (value < 0.34) return labels[0];
  if (value < 0.67) return labels[1];
  return labels[2];
}

function interactionStyle(context) {
  const stress = band(context.actor.stress, ["relatively settled", "concerned", "highly stressed"]);
  const informationNeed = band(context.actor.informationNeed, ["low information need", "seeking clarification", "strong need for clear information"]);
  const controlImpulse = band(context.actor.controlImpulse, ["low urge to take control", "some urge to take control", "strong urge to take control"]);
  const roleClarity = band(context.actor.roleClarity, ["uncertain about their role", "partly clear about their role", "clear about their role"]);

  return [
    "Simulation interaction style only; do not treat this as a psychological diagnosis or fixed personality.",
    `Current state: ${stress}; ${informationNeed}; ${controlImpulse}; ${roleClarity}.`,
    "Address the patient directly when the patient is participating.",
    "Do not infer incapacity from AAC use, delayed response, distress, disability, or relational stress.",
    "Family/supporter presence does not create substitute decision-making authority.",
    "Respect explicit privacy and communication boundaries."
  ].join(" ");
}

/**
 * Build a payload compatible with AI Roleplay Chat Simulator start-conversation.
 * This function is read-only: role-play prose never mutates deterministic relational state.
 */
export function buildAIRoleplayStartPayload(state, {
  userActorId = state.patientId,
  otherActorId,
  topic = "Family communication during critical illness",
  userInitialMessage
} = {}) {
  const userActor = assertActor(state, userActorId, "userActorId");
  const otherActor = assertActor(state, otherActorId, "otherActorId");
  const context = deriveRoleplayContext(state, otherActorId, userActorId);

  const payload = {
    user: { name: userActor.label },
    otherPerson: {
      name: otherActor.label,
      role: otherActor.role,
      personality: interactionStyle(context)
    },
    conversation: { topic }
  };

  if (typeof userInitialMessage === "string" && userInitialMessage.trim()) {
    payload.userInitialMessage = userInitialMessage.trim();
  }

  return {
    payload,
    context,
    mode: "read-only-dialogue",
    deterministicStateMutationAllowed: false,
    stateFingerprint: JSON.stringify(summarizeRelationalState(state))
  };
}

/**
 * Prepare the contract for one AI Roleplay Chat Simulator continue-conversation call.
 * The message itself may be generated by a dialogue model, but it cannot create a
 * relational event. A facilitator/scenario controller must separately commit a typed event.
 */
export function buildAIRoleplayContinuePayload({ otherPersonMessage, possibleUserResponses }) {
  if (typeof otherPersonMessage !== "string" || !otherPersonMessage.trim()) {
    throw new TypeError("otherPersonMessage must be a non-empty string.");
  }
  if (!Array.isArray(possibleUserResponses) || possibleUserResponses.length < 2 || possibleUserResponses.length > 4) {
    throw new RangeError("possibleUserResponses must contain between 2 and 4 responses.");
  }
  const responses = possibleUserResponses.map((item, index) => {
    if (typeof item !== "string" || !item.trim()) {
      throw new TypeError(`possibleUserResponses[${index}] must be a non-empty string.`);
    }
    return item.trim();
  });

  return {
    otherPersonMessage: otherPersonMessage.trim(),
    possibleUserResponses: responses
  };
}

/**
 * Generation context for an LLM or role-play service. The service may render dialogue,
 * but only explicit structured events handled by applyRelationalEvent may change state.
 */
export function buildRoleplayGenerationEnvelope(state, {
  speakingActorId,
  listeningActorId = state.patientId,
  sceneGoal = "Render a plausible family interaction without taking decision authority away from the patient."
} = {}) {
  assertActor(state, speakingActorId, "speakingActorId");
  assertActor(state, listeningActorId, "listeningActorId");
  const context = deriveRoleplayContext(state, speakingActorId, listeningActorId);

  return {
    sceneGoal,
    context,
    permittedOutput: ["dialogue", "emotionally plausible hesitation", "questions", "repair attempts"],
    forbiddenInference: [
      "decision-making incapacity from disability or AAC use",
      "legal substitute authority from family presence",
      "treatment futility from stress, conflict, dependency, or quality-of-life assumptions",
      "clinical treatment choice from relational state"
    ],
    stateMutationRule: "Dialogue output is descriptive only. Commit state changes through an explicit RELATIONAL_EVENT_TYPES event after scenario/facilitator validation.",
    provenance: {
      adapter: "AI_Roleplay_Chat_Simulator",
      deterministicRelationalState: "biosocial-relational-substrate",
      rightsAuthority: "external Patient Autonomy and Rights Safeguards gate"
    }
  };
}
